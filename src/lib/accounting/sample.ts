type SampleInput = Partial<EntryForm> & Pick<EntryForm, 'book' | 'date'>

const make = (no: number, p: SampleInput): Entry => {
  const f = { ...emptyForm(p.book, p.date), ...p }
  return {
    ...formToEntry(f),
    id: `sample-${String(no).padStart(2, '0')}`,
    createdAt: no,
  }
}

const gl = (account: string, dr: string, cr: string, partyId = '') => ({
  account,
  dr,
  cr,
  partyId,
})

